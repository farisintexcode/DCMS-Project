import { expect, test } from './fixtures';

test('Rider can start assigned work save a validated visit and review a blocked proof checklist', async ({ page }) => {
    const email=process.env.DCMS_E2E_RIDER_EMAIL;
    const password=process.env.DCMS_E2E_PASSWORD;
    test.skip(!email||!password,'Use isolated synthetic Rider fixtures.');
    const surface=test.info().project.name;
    const faults:string[]=[];
    page.on('pageerror',error=>faults.push(error.message));
    await page.goto('/rider/login');
    await page.getByLabel('Email',{exact:true}).fill(email!);
    await page.getByLabel('Password',{exact:true}).fill(password!);
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await expect(page).toHaveURL(/\/rider$/,{timeout:90000});
    await expect(page.getByText('Pending verification',{exact:true}).first()).toBeVisible();
    await page.goto('/rider/tasks');
    await page.getByLabel('Account or customer reference',{exact:true}).fill('M06-'+surface.toUpperCase());
    await page.getByRole('button',{name:'Search',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Synthetic Field Customer '+surface,exact:true})).toBeVisible();
    await expect(page.getByRole('link',{name:'View Task',exact:true})).toHaveCount(1);
    await page.getByRole('link',{name:'View Task',exact:true}).click();
    await page.getByRole('button',{name:'Start Task',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Record site visit',exact:true})).toBeVisible();
    await page.getByLabel('Customer availability',{exact:true}).selectOption('available');
    await page.getByLabel('Site status',{exact:true}).selectOption('operating');
    await page.getByLabel('Contact result',{exact:true}).selectOption('call_back_requested');
    await page.getByLabel('Visit outcome',{exact:true}).selectOption('successful_visit');
    await page.getByLabel('Site address / location',{exact:true}).fill('10 Synthetic field road');
    await page.getByLabel('Visit remarks',{exact:true}).fill('Synthetic browser visit '+surface);
    await page.getByRole('button',{name:'Save visit & remarks',exact:true}).click();
    await expect(page.getByRole('alert')).toContainText('A due follow-up is required');
    await page.getByRole('button',{name:'OK',exact:true}).click();
    await expect(page.getByLabel('Visit remarks',{exact:true})).toHaveValue('Synthetic browser visit '+surface);
    await page.getByLabel('Contact result',{exact:true}).selectOption('customer_contacted');
    await page.getByLabel('Visit outcome',{exact:true}).selectOption('payment_claimed');
    const input=page.getByLabel('Visit time (MYT)',{exact:true});
    const inputBounds=await input.boundingBox();
    const cardBounds=await input.locator('xpath=ancestor::form').boundingBox();
    expect(inputBounds!.x).toBeGreaterThanOrEqual(cardBounds!.x);
    expect(inputBounds!.x+inputBounds!.width).toBeLessThanOrEqual(cardBounds!.x+cardBounds!.width+1);
    await page.screenshot({path:'.local-tools/m06-'+surface+'-visit.png',fullPage:true});
    await page.getByRole('button',{name:'Save visit & remarks',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Proof images',exact:true})).toBeVisible();
    await expect(page.getByText('Private S3 storage is not configured.',{exact:false})).toBeVisible();
    await expect(page.getByLabel('Choose images from camera or gallery',{exact:true})).toBeDisabled();
    await page.getByRole('button',{name:'Review completion checklist',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Completion review',exact:true})).toBeVisible();
    await expect(page.getByRole('button',{name:'Submit Completion · resolve checklist first',exact:true})).toBeDisabled();
    await expect(page.getByText('Synthetic browser visit '+surface,{exact:true})).toBeVisible();
    await page.screenshot({path:'.local-tools/m06-'+surface+'-checklist.png',fullPage:true});
    await page.getByRole('button',{name:'History',exact:true}).click();
    await expect(page.getByText('Synthetic browser visit '+surface,{exact:true})).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
    expect(faults).toEqual([]);
});

