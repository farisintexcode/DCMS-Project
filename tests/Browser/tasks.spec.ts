import { expect, test } from './fixtures';

test('customer account manual task editing and exact allocation preview are usable on desktop and mobile', async ({ page }) => {
    test.setTimeout(90000);
    const email = process.env.DCMS_E2E_ADMIN_EMAIL;
    const password = process.env.DCMS_E2E_PASSWORD;
    test.skip(!email || !password, 'Use isolated synthetic task fixtures.');
    const account = `000TASK-${test.info().project.name}-${test.info().retry}`;
    await page.goto('/login');
    await page.getByLabel('Email', { exact: true }).fill(email!);
    await page.getByLabel('Password', { exact: true }).fill(password!);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page).toHaveURL(/\/admin$/, { timeout: 90000 });
    await page.goto('/admin/customers');
    await page.getByLabel('Search by', { exact: true }).selectOption('reference');
    await page.getByLabel('Search customers', { exact: true }).fill('TASK-UI');
    await page.getByRole('link', { name: /^(TASK-UI|Synthetic Task Customer)$/ }).filter({ visible: true }).click();
    await page.getByRole('button', { name: 'Accounts', exact: true }).click();
    await page.getByRole('link', { name: 'Add account', exact: true }).click();
    await page.getByLabel('Account number *', { exact: true }).fill(account);
    await page.getByLabel('Customer relationship *', { exact: true }).selectOption('billing_customer');
    await page.getByLabel('Service address', { exact: true }).fill('10 Synthetic Task Road');
    await page.getByLabel('Postcode', { exact: true }).fill('00001');
    await page.getByRole('button', { name: 'Save account', exact: true }).click();
    await expect(page.getByRole('heading', { name: account, exact: true })).toBeVisible();
    await page.goto('/admin/tasks/create');
    await page.getByLabel('Assignment batch *', { exact: true }).selectOption({ label: 'Synthetic Task Batch · domestic_dr' });
    await page.getByLabel('Customer *', { exact: true }).selectOption({ label: 'TASK-UI · Synthetic Task Customer' });
    await page.getByLabel('Service account *', { exact: true }).selectOption({ label: `${account} · active` });
    await page.getByLabel('Planned visit (MYT)', { exact: true }).fill('2026-10-20T09:30');
    await page.getByLabel('Due date & time (MYT)', { exact: true }).fill('2026-10-21T17:30');
    await page.getByLabel('Special instructions', { exact: true }).fill('Synthetic task instructions');
    await page.getByRole('button', { name: 'Save task', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Task details', exact: true })).toBeVisible();
    await page.getByRole('link', { name: 'Edit task', exact: true }).click();
    await expect(page.getByLabel('Service account *', { exact: true })).toBeDisabled();
    await page.getByLabel('Priority *', { exact: true }).selectOption('urgent');
    await page.getByRole('button', { name: 'Update task', exact: true }).click();
    await expect(page.getByText('Urgent', { exact: true })).toBeVisible();
    await page.getByRole('link', { name: 'Review task operation', exact: true }).click();
    const receivingRider = await page.getByLabel('Receiving Rider *', { exact: true }).locator('option').filter({ hasText: 'Field Rider' }).getAttribute('value');
    await page.getByLabel('Receiving Rider *', { exact: true }).selectOption(receivingRider!);
    await page.getByLabel('Operation reason *', { exact: true }).fill('Synthetic reviewed field allocation');
    await page.getByRole('button', { name: 'Prepare operation preview', exact: true }).click();
    await expect(page.getByText('Eligible at preview', { exact: true })).toBeVisible();
    await page.screenshot({ path: test.info().outputPath('task-operation-preview.png'), fullPage: true });
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Confirm 1 eligible tasks', exact: true }).click();
    await expect(page.getByText('Queued', { exact: true })).toBeVisible();
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download operation results', exact: true }).click();
    expect((await download).suggestedFilename()).toMatch(/^task-operation-.*\.csv$/);
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Cancel outstanding items', exact: true }).click();
    await expect(page.getByText('Cancelled', { exact: true })).toBeVisible();
    await page.goto('/admin/tasks');
    await page.getByLabel('Exact task / account / customer reference', { exact: true }).fill(account);
    await expect(page.getByRole('link', { name: 'View task', exact: true }).filter({ visible: true })).toHaveCount(1);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    for (const label of ['Created from', 'Created until']) {
        expect(await page.getByLabel(label, { exact: true }).evaluate(element => {
            const input = element.getBoundingClientRect();
            const card = element.closest('.surface')!.getBoundingClientRect();
            return input.left >= card.left && input.right <= card.right;
        })).toBe(true);
    }
    await page.screenshot({ path: test.info().outputPath('task-monitoring.png'), fullPage: true });
});
