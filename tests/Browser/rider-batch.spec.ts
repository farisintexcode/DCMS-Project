import { expect, test } from './fixtures';

test('Rider previews selected batch updates and retains verification safeguards', async ({ page }) => {
    const email = process.env.DCMS_E2E_RIDER_EMAIL;
    const password = process.env.DCMS_E2E_PASSWORD;
    test.skip(!email || !password, 'Requires disposable synthetic Rider fixtures.');
    const surface = test.info().project.name;
    const faults: string[] = [];
    page.on('pageerror', error => faults.push(error.message));
    await page.goto('/rider/login');
    await page.getByLabel('Email', { exact: true }).fill(email!);
    await page.getByLabel('Password', { exact: true }).fill(password!);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page).toHaveURL(/\/rider$/);
    await page.goto('/rider/tasks');
    await page.getByLabel('Account or customer reference', { exact: true }).fill('M06-' + surface.toUpperCase());
    await page.getByRole('button', { name: 'Search', exact: true }).click();
    await expect(page.getByRole('link', { name: 'View Task', exact: true })).toHaveCount(1);
    await page.getByRole('link', { name: 'View Task', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Task details', exact: true })).toBeVisible();
    const taskUrl = page.url();
    await page.getByRole('button', { name: 'Start Task', exact: true }).click();
    await page.getByLabel('Customer availability', { exact: true }).selectOption('available');
    await page.getByLabel('Site status', { exact: true }).selectOption('operating');
    await page.getByLabel('Contact result', { exact: true }).selectOption('customer_contacted');
    await page.getByLabel('Visit outcome', { exact: true }).selectOption('successful_visit');
    await page.getByLabel('Site address / location', { exact: true }).fill('Synthetic field address');
    await page.getByLabel('Visit remarks', { exact: true }).fill('Synthetic batch field observation');
    await page.getByRole('button', { name: 'Save visit & remarks', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Proof images', exact: true })).toBeVisible();

    await page.goto('/rider/tasks/manage');
    await page.getByRole('combobox', { name: 'Assignment', exact: true }).selectOption({ label: 'Synthetic Rider Batch ' + surface });
    await page.getByLabel('Type of manage', { exact: true }).selectOption('dr_code');
    await page.getByLabel('New value', { exact: true }).selectOption('DR05');
    await page.getByLabel('Reason / explanation', { exact: true }).fill('Confirmed during the synthetic visit');
    const selection = page.getByRole('checkbox', { name: 'Select M06-' + surface.toUpperCase(), exact: true });
    await selection.check();
    await page.getByRole('button', { name: 'Preview selected update', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Review selected update', exact: true })).toBeVisible();
    await expect(page.getByText('Not recorded → DR05', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Review selected update', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Preview selected update', exact: true }).click();
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Apply selected update', exact: true }).click();
    await expect(selection).not.toBeChecked();
    await page.goto(taskUrl + '?section=visit');
    await page.getByText('DR code & property observations', { exact: true }).click();
    await expect(page.getByLabel('DR code', { exact: true })).toHaveValue('DR05');

    await page.goto('/rider/tasks/manage');
    await page.getByRole('combobox', { name: 'Assignment', exact: true }).selectOption({ label: 'Synthetic Rider Batch ' + surface });
    await page.getByLabel('Type of manage', { exact: true }).selectOption('business_nature');
    await expect(page.getByLabel('New value', { exact: true }).locator('option[value="NB01"]')).toHaveText('NB01 · Hardware Shop');
    await page.getByLabel('Type of manage', { exact: true }).selectOption('property_type');
    await expect(page.getByText('No approved options are configured for this field.', { exact: false })).toBeVisible();
    await page.getByLabel('Type of manage', { exact: true }).selectOption('submit');
    await page.getByLabel('Reason / explanation', { exact: true }).fill('Request verification of the saved work');
    await selection.check();
    await page.getByRole('button', { name: 'Preview selected update', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Apply selected update', exact: true })).toBeDisabled();
    await expect(page.getByText('Eligible tasks will become Pending Verification.', { exact: false })).toBeVisible();
    await page.getByText('Saved visit, remarks & proof', { exact: true }).click();
    await expect(page.getByText('Synthetic batch field observation', { exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath('batch-blocked-completion.png'), fullPage: true });
    await page.getByRole('button', { name: 'Menu', exact: true }).click();
    await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).click();
    await page.keyboard.press('Escape');
    await page.screenshot({ path: test.info().outputPath('batch-dark.png'), fullPage: true });
    expect(faults).toEqual([]);
});
