import { expect, test } from './fixtures';

test('Rider profile and settings stay separate and appearance persists across the workspace', async ({ page }) => {
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.emulateMedia({ colorScheme: 'light' });
    await page.goto('/rider/login');
    await page.getByLabel('Email', { exact: true }).fill(process.env.DCMS_E2E_RIDER_EMAIL!);
    await page.getByLabel('Password', { exact: true }).fill(process.env.DCMS_E2E_PASSWORD!);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page).toHaveURL(/\/rider$/);
    const dashboardWidth = (await page.locator('main').boundingBox())!.width;
    await page.goto('/rider/profile');
    await expect(page.getByRole('heading', { name: 'My Profile', exact: true })).toBeVisible();
    expect((await page.locator('main').boundingBox())!.width).toBe(dashboardWidth);
    await expect(page.locator('.rider-profile-header')).toHaveCSS('background-color', 'rgb(2, 48, 71)');
    await expect(page.getByRole('heading', { name: 'Personal information' })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Edit profile photo' })).toBeVisible();
    await expect(page.getByLabel('Current Password', { exact: true })).toHaveCount(0);
    await expect(page.locator('main .eyebrow')).toHaveCount(0);
    await expect(page.getByRole('navigation', { name: 'Rider navigation', exact: true }).getByRole('link')).toHaveText(['Home', 'Assignment', 'My Task', 'Attendance']);
    await page.screenshot({ path: test.info().outputPath('rider-profile-light.png'), fullPage: true });
    await page.goto('/account');
    await expect(page.getByRole('heading', { name: 'Account Settings', exact: true })).toBeVisible();
    expect((await page.locator('main').boundingBox())!.width).toBe(dashboardWidth);
    await expect(page.getByRole('button', { name: 'Edit profile photo' })).toHaveCount(0);
    await expect(page.getByRole('radio')).toHaveCount(3);
    await expect(page.getByLabel('Current Password', { exact: true })).toHaveAttribute('type', 'password');
    await page.getByRole('button', { name: 'Show password', exact: true }).first().click();
    await expect(page.getByLabel('Current Password', { exact: true })).toHaveAttribute('type', 'text');
    await page.getByRole('button', { name: 'Hide password', exact: true }).click();
    await page.getByRole('radio', { name: 'Dark Mode' }).check();
    await expect(page.locator('html')).toHaveClass(/dark/);
    await page.reload();
    await expect(page.getByRole('radio', { name: 'Dark Mode' })).toBeChecked();
    await page.screenshot({ path: test.info().outputPath('rider-settings-dark.png'), fullPage: true });
    await page.goto('/rider/profile');
    await expect(page.locator('html')).toHaveClass(/dark/);
    await page.screenshot({ path: test.info().outputPath('rider-profile-dark.png'), fullPage: true });
    await page.goto('/account');
    await page.getByRole('radio', { name: 'Light Mode' }).check();
    await expect(page.locator('html')).not.toHaveClass(/dark/);
    await page.getByRole('radio', { name: 'System Default' }).check();
    await page.emulateMedia({ colorScheme: 'dark' });
    await expect(page.locator('html')).toHaveClass(/dark/);
    await page.reload();
    await expect(page.getByRole('radio', { name: 'System Default' })).toBeChecked();
    await page.emulateMedia({ colorScheme: 'light' });
    await expect(page.locator('html')).not.toHaveClass(/dark/);
    await page.screenshot({ path: test.info().outputPath('rider-settings-light.png'), fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    expect(errors).toEqual([]);
});
